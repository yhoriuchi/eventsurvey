#' eventsurvey: Causal Inference for Events During Surveys
#'
#' The package provides a guided workflow for estimating period-specific and
#' window-average effects when an event occurs during survey
#' fieldwork. The core method forecasts the no-event outcome path from
#' pre-event observations and uses rolling placebo forecasts to assess
#' extrapolation error. The estimator uses a local linear time model, optionally
#' with additive baseline covariates for respondent-level data, and honest
#' bounded-misspecification-error inference.
#'
